#!/usr/bin/env python3
"""Generates docs/icon.svg: twin exhaust tips in three-quarter view, white line
art on black. Render to the asset catalog with Tools/render_icon.sh."""
import math, os

OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "icon.svg")

ANGLE = math.radians(-24)                     # pipes run up-right into the car
D = (math.cos(ANGLE), math.sin(ANGLE))        # along the pipe
N = (-D[1], D[0])                             # across the pipe (car's lateral axis)
R_MAJOR, R_MINOR = 128, 58                    # opening ellipse as seen at an angle
LENGTH = 380
ROT = math.degrees(math.atan2(N[1], N[0]))   # ellipse x-axis (major) along N, across the pipe


def p(c, a, b):
    return (c[0] + D[0] * a + N[0] * b, c[1] + D[1] * a + N[1] * b)


def f(pt):
    return f"{pt[0]:.1f} {pt[1]:.1f}"


def pipe(c):
    top, bot = p(c, 0, -R_MAJOR), p(c, 0, R_MAJOR)
    top_end, bot_end = p(c, LENGTH, -R_MAJOR), p(c, LENGTH, R_MAJOR)
    body = (f'<path d="M{f(top)} L{f(top_end)} L{f(bot_end)} L{f(bot)} Z" fill="#000" stroke="none"/>'
            f'<path d="M{f(top)} L{f(top_end)} M{f(bot)} L{f(bot_end)}" stroke-width="20"/>')
    # A band where the tip meets the pipe
    band_a, band_b = p(c, 70, -R_MAJOR), p(c, 70, R_MAJOR)
    band = (f'<path d="M{f(band_a)} A{R_MAJOR} {R_MINOR} {ROT:.1f} 0 1 {f(band_b)}" '
            f'stroke-width="8" opacity="0.6"/>')
    tip = (f'<ellipse cx="{c[0]:.1f}" cy="{c[1]:.1f}" rx="{R_MAJOR}" ry="{R_MINOR}" '
           f'transform="rotate({ROT:.1f} {c[0]:.1f} {c[1]:.1f})" fill="#000" stroke-width="28"/>'
           f'<ellipse cx="{c[0] + D[0] * 6:.1f}" cy="{c[1] + D[1] * 6:.1f}" rx="{R_MAJOR * 0.74:.1f}" ry="{R_MINOR * 0.62:.1f}" '
           f'transform="rotate({ROT:.1f} {c[0]:.1f} {c[1]:.1f})" stroke-width="9"/>')
    flow = []
    for k, length in ((-62, 110), (0, 160), (62, 110)):
        a = p(c, -R_MINOR - 40, k)
        b = p(c, -R_MINOR - 40 - length, k * 1.25)
        flow.append(f'<path d="M{f(a)} L{f(b)}" stroke-width="14" opacity="0.85"/>')
    return body + band + tip + "".join(flow)


c_back = (335, 420)
c_front = p(c_back, 0, 300)
c_front = (c_front[0] + 10, c_front[1])

# Bumper / valance edge that the pipes disappear behind.
v1 = p(c_back, LENGTH - 10, -R_MAJOR - 130)
v2 = p(c_front, LENGTH - 10, R_MAJOR + 140)
ctrl = p(((v1[0] + v2[0]) / 2, (v1[1] + v2[1]) / 2), -70, 0)
valance = (f'<path d="M{f(v1)} Q{f(ctrl)} {f(v2)} L1080 1080 L1080 -60 Z" fill="#000" stroke="none"/>'
           f'<path d="M{f(v1)} Q{f(ctrl)} {f(v2)}" stroke-width="18"/>'
           f'<path d="M{f(p(v1, 70, 0))} Q{f(p(ctrl, 70, 0))} {f(p(v2, 70, 0))}" stroke-width="8" opacity="0.5"/>')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <!-- Brumbrum app icon, generated by Tools/make_icon.py: twin exhaust tips in
       three-quarter view, white line art on black. -->
  <rect width="1024" height="1024" fill="#000"/>
  <g fill="none" stroke="#fff" stroke-linecap="round" stroke-linejoin="round">
    {pipe(c_back)}
    {pipe(c_front)}
    {valance}
  </g>
</svg>
'''
with open(OUT, "w") as fh:
    fh.write(svg)
print("wrote", OUT)
